/**
 * `pull` — read the current CT catalog and write it back to disk as a CatalogBundle, and
 * optionally emit a TypeScript stub of the contract-typed arrays.
 *
 * Used once to migrate an existing CT catalog (authored in the old MC editors) into host
 * code, and thereafter for the parity check (pulled CT === host `buildCatalog()` output).
 */

import * as fs from 'node:fs';
import * as path from 'node:path';
import {
  type CatalogBundle,
  type CatalogKey,
  type CombinedCatalog,
} from '../contract.js';
import { getCustomObject } from '../core/ct-client.js';
import { extractPayload } from '../catalog/envelope.js';
import { ALL_KEYS, type SyncContext } from './context.js';

export type PullOptions = {
  ctx: SyncContext;
  only?: CatalogKey[];
  /** File (bundle JSON) or directory (per-key JSON files) to write. */
  out: string;
  /** When set, also write a contract-typed .ts stub here. */
  stubs?: string;
};

export type PullResult = {
  bundle: CatalogBundle;
  perKey: Array<{ key: CatalogKey; found: boolean }>;
  wrote: string[];
};

function emptyBundle(): CatalogBundle {
  return {
    components: { groups: [], components: [] },
    'data-sources': { groups: [], sources: [] },
    sections: { sections: [] },
  };
}

export async function runPull(opts: PullOptions): Promise<PullResult> {
  const { ctx } = opts;
  const keys = opts.only?.length ? opts.only : ALL_KEYS;
  const bundle = emptyBundle();
  const perKey: PullResult['perKey'] = [];

  // One distinct custom object per key and nothing but reads, so fetch them
  // together; `Promise.all` keeps the results in `keys` order.
  const fetched = await Promise.all(
    keys.map((key) =>
      getCustomObject<CombinedCatalog<unknown>>(ctx.env, ctx.token, key)
    )
  );
  keys.forEach((key, i) => {
    const existing = fetched[i];
    const payload = existing ? extractPayload(existing.value) : null;
    if (payload) {
      // The payload shape matches the key's payload type.
      (bundle as Record<string, unknown>)[key] = payload;
    }
    perKey.push({ key, found: Boolean(payload) });
  });

  const wrote: string[] = [];
  const out = path.resolve(process.cwd(), opts.out);
  if (out.endsWith(path.sep) || (fs.existsSync(out) && fs.statSync(out).isDirectory())) {
    fs.mkdirSync(out, { recursive: true });
    for (const key of keys) {
      const file = path.join(out, `${key}.json`);
      fs.writeFileSync(file, JSON.stringify(bundle[key], null, 2) + '\n');
      wrote.push(file);
    }
  } else {
    fs.mkdirSync(path.dirname(out), { recursive: true });
    fs.writeFileSync(out, JSON.stringify(bundle, null, 2) + '\n');
    wrote.push(out);
  }

  if (opts.stubs) {
    const stubPath = path.resolve(process.cwd(), opts.stubs);
    fs.mkdirSync(path.dirname(stubPath), { recursive: true });
    fs.writeFileSync(stubPath, emitStub(bundle));
    wrote.push(stubPath);
  }

  return { bundle, perKey, wrote };
}

/**
 * A starting-point TS module exporting the pulled definitions as contract-typed arrays.
 * The host adapts these into co-located `defineBlock` / `defineDataSource` registrations
 * (see the host authoring guide) rather than importing this file directly at runtime.
 */
function emitStub(bundle: CatalogBundle): string {
  const j = (v: unknown) => JSON.stringify(v, null, 2);
  return `/* AUTO-GENERATED by \`page-builder-sync pull --stubs\`.
 * A migration starting point: move each entry into its co-located component/resolver
 * registration, then delete this file. Do not import it at runtime. */
import type {
  ComponentGroup,
  ComponentType,
  DataSourceGroup,
  DataSourceType,
  Section,
} from '@commercetools-labs/page-builder/contract';

export const COMPONENT_GROUPS: ComponentGroup[] = ${j(bundle.components.groups)};

export const COMPONENTS: ComponentType[] = ${j(bundle.components.components)};

export const DATA_SOURCE_GROUPS: DataSourceGroup[] = ${j(bundle['data-sources'].groups)};

export const DATA_SOURCES: DataSourceType[] = ${j(bundle['data-sources'].sources)};

export const SECTIONS: Section[] = ${j(bundle.sections.sections)};
`;
}
